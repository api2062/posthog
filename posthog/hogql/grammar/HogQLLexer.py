    def isOpeningTag(self) -> bool:
        ch1 = self._peek_char(1)
        if not (ch1.isalpha() or ch1 == '_'):
            return False                           # not a tag name start

        # skip tag name
        i = 2
        while True:
            ch = self._peek_char(i)
            if ch.isalnum() or ch in ('_', '-'):
                i += 1
            else:
                break

